import { test, expect } from '@playwright/test';
import { login, ready } from './helpers';
for (const width of [1440, 390])
  test(`Menu avatar ${width}px: hồ sơ, trang chính, bàn phím và đăng xuất`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await login(page, 'manager');
    await ready(page);
    const trigger = page.getByRole('button', { name: 'Menu tài khoản', exact: true });
    await trigger.click();
    const menu = page.getByRole('menu', { name: 'Tùy chọn tài khoản' });
    await expect(menu).toBeVisible();
    await expect(trigger).toHaveAttribute('aria-expanded', 'true');
    await expect(page.locator('.account-menu-summary')).toContainText('manager@gpp.demo');
    await expect(page.locator('.account-menu-scope')).toContainText('Nhà thuốc An Tâm');
    const box = await page.locator('.account-dropdown').boundingBox();
    expect(box!.x).toBeGreaterThanOrEqual(0);
    expect(box!.x + box!.width).toBeLessThanOrEqual(width);
    await menu.getByRole('menuitem', { name: /Thông tin tài khoản/ }).click();
    await expect(page).toHaveURL(/\/account$/);
    await expect(menu).toBeHidden();
    await trigger.focus();
    await page.keyboard.press('ArrowUp');
    await expect(menu.getByRole('menuitem', { name: 'Đăng xuất', exact: true })).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(menu).toBeHidden();
    await expect(trigger).toBeFocused();
    await trigger.click();
    await page.locator('.app-footer').click();
    await expect(menu).toBeHidden();
    await trigger.focus();
    await page.keyboard.press('ArrowDown');
    await expect(menu.getByRole('menuitem', { name: /Thông tin tài khoản/ })).toBeFocused();
    await page.keyboard.press('ArrowDown');
    await expect(menu.getByRole('menuitem', { name: /Không gian làm việc/ })).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(page).toHaveURL(/\/overview$/);
    await trigger.click();
    await menu.getByRole('menuitem', { name: 'Đăng xuất', exact: true }).click();
    await expect(page).toHaveURL(/\/login$/);
    expect((await page.request.get('/api/auth/me')).status()).toBe(401);
  });
